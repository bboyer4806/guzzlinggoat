<p class="lead">
	Local Ethiopian legend tells the story of a goat farmer who was missing goats from his herd during
	the day. These goats would return with a tremendous spring in their step. After following these
	mischievous goats, he discovered that they were eating a strange bean from a bush. He ate the
	beans himself, and coffee was discovered.
